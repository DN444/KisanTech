export function exportCSVReport(title, data) {
  let csvRows = [];
  if (Array.isArray(data)) {
    if (data.length > 0 && typeof data[0] === 'object') {
      const headers = Object.keys(data[0]);
      csvRows.push(headers.join(','));
      for (const row of data) {
        const values = headers.map(header => {
          const val = row[header];
          return `"${String(val ?? '').replace(/"/g, '""')}"`;
        });
        csvRows.push(values.join(','));
      }
    }
  } else if (typeof data === 'object' && data !== null) {
    csvRows.push('Metric,Value');
    for (const [key, val] of Object.entries(data)) {
      csvRows.push(`"${key}","${String(val).replace(/"/g, '""')}"`);
    }
  } else {
    csvRows.push('Content');
    csvRows.push(`"${String(data).replace(/"/g, '""')}"`);
  }

  const csvContent = '\ufeff' + csvRows.join('\n');
  downloadBlob(csvContent, `KisanTech_${cleanFilename(title)}.csv`, 'text/csv;charset=utf-8');
}

