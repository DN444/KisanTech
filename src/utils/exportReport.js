function cleanFilename(str) {
  return String(str || 'Report').replace(/[^a-zA-Z0-9_\-]/g, '_');
}

function downloadBlob(content, filename, contentType) {
  const blob = new Blob([content], { type: contentType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

function buildHTMLTable(data) {
  if (Array.isArray(data)) {
    if (data.length === 0) return '<p>No records available.</p>';
    if (typeof data[0] === 'object' && data[0] !== null) {
      const headers = Object.keys(data[0]);
      return `
        <table>
          <thead>
            <tr>${headers.map(h => `<th>${h}</th>`).join('')}</tr>
          </thead>
          <tbody>
            ${data.map(row => `
              <tr>${headers.map(h => `<td>${row[h] !== undefined ? String(row[h]) : ''}</td>`).join('')}</tr>
            `).join('')}
          </tbody>
        </table>
      `;
    }
    return `<ul>${data.map(item => `<li>${String(item)}</li>`).join('')}</ul>`;
  }
  if (typeof data === 'object' && data !== null) {
    const entries = Object.entries(data);
    return `
      <table>
        <thead>
          <tr><th>Parameter</th><th>Value</th></tr>
        </thead>
        <tbody>
          ${entries.map(([k, v]) => `
            <tr><td><strong>${k}</strong></td><td>${typeof v === 'object' ? JSON.stringify(v) : String(v)}</td></tr>
          `).join('')}
        </tbody>
      </table>
    `;
  }
  return `<p>${String(data)}</p>`;
}
